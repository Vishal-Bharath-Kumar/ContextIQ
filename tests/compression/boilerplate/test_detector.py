_TS = datetime(2024, 1, 1, tzinfo=UTC)


def _meta(file_path: str = "a/b.py") -> ChunkMetadata:
    return ChunkMetadata(file_path=file_path, timestamp=_TS, author="tester")


def _chunk(
    chunk_id: str,
    content: str,
    source_id: str = "github",
    score: float = 0.9,
) -> RetrievedChunk:
    return RetrievedChunk(
        chunk_id=chunk_id,
        source_id=source_id,
        content=content,
        score=score,
        metadata=_meta(),
    )


