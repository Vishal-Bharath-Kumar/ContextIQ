class TestCustomRules:
    def test_custom_rule_matches(self) -> None:
        rules = [BoilerplateRule(name="acme_header", pattern=r"ACME CORP CONFIDENTIAL")]
        detector = BoilerplateDetector(rules=rules)
        assert detector.matching_rule("ACME CORP CONFIDENTIAL — internal use only") == "acme_header"

    def test_disabled_rule_is_skipped(self) -> None:
        rules = [
            BoilerplateRule(name="active", pattern=r"ONLY_ACTIVE_MARKER"),
            BoilerplateRule(name="inactive", pattern=r"ONLY_INACTIVE_MARKER", enabled=False),
        ]
        detector = BoilerplateDetector(rules=rules)
        assert detector.matching_rule("ONLY_INACTIVE_MARKER content") is None
        assert detector.matching_rule("ONLY_ACTIVE_MARKER content") == "active"

    def test_patterns_precompiled_at_init(self) -> None:
        detector = BoilerplateDetector()
        import re

        assert all(
            isinstance(pat, re.Pattern) for _, pat in detector._compiled
        )


