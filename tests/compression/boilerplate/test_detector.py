class TestFilter:
    def test_boilerplate_chunk_is_removed(self) -> None:
        detector = BoilerplateDetector()
        chunks = [_chunk("c1", "// SPDX-License-Identifier: Apache-2.0")]
        kept, removed = detector.filter(chunks)
        assert kept == []
        assert len(removed) == 1
        assert removed[0].chunk_id == "c1"
        assert removed[0].reason == RemovalReason.BOILERPLATE
        assert removed[0].boilerplate_rule == "spdx_license_header"

    def test_clean_chunk_is_kept(self) -> None:
        detector = BoilerplateDetector()
        chunks = [_chunk("c2", "def foo(): return 42")]
        kept, removed = detector.filter(chunks)
        assert len(kept) == 1
        assert removed == []

    def test_removed_chunk_has_original_content(self) -> None:
        content = "// SPDX-License-Identifier: MIT\nsome code"
        detector = BoilerplateDetector()
        _, removed = detector.filter([_chunk("c3", content)])
        assert removed[0].original_content == content

    def test_mixed_chunks_partitioned_correctly(self) -> None:
        detector = BoilerplateDetector()
        chunks = [
            _chunk("clean1", "def add(a, b): return a + b"),
            _chunk("bp1", "// SPDX-License-Identifier: MIT"),
            _chunk("clean2", "class Foo: pass"),
            _chunk("bp2", "// This file was generated — DO NOT EDIT"),
        ]
        kept, removed = detector.filter(chunks)
        assert [c.chunk_id for c in kept] == ["clean1", "clean2"]
        assert [r.chunk_id for r in removed] == ["bp1", "bp2"]

    def test_empty_input_returns_empty_lists(self) -> None:
        detector = BoilerplateDetector()
        kept, removed = detector.filter([])
        assert kept == []
        assert removed == []


