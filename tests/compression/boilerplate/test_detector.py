# BoilerplateSettings — env-var rule extension
# ---------------------------------------------------------------------------


class TestBoilerplateSettings:
    def test_extra_rule_added_via_env(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setenv("BOILERPLATE_EXTRA_RULES", "my_rule|ACME CORP CONFIDENTIAL")
        settings = BoilerplateSettings()
        rules = settings.get_rules()
        names = [r.name for r in rules]
        assert "my_rule" in names

    def test_disabled_rule_set_to_inactive(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setenv("BOILERPLATE_DISABLED_RULES", "maven_build_output")
        settings = BoilerplateSettings()
        rules = settings.get_rules()
        maven_rule = next(r for r in rules if r.name == "maven_build_output")
        assert maven_rule.enabled is False

    def test_disabled_rule_not_matched_by_detector(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setenv("BOILERPLATE_DISABLED_RULES", "maven_build_output")
        settings = BoilerplateSettings()
        detector = BoilerplateDetector(rules=settings.get_rules())
        assert detector.matching_rule("[INFO] --- maven-compiler-plugin") is None

    def test_multiple_extra_rules_semicolon_separated(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setenv(
            "BOILERPLATE_EXTRA_RULES",
            "rule_a|PATTERN_A;rule_b|PATTERN_B",
        )
        settings = BoilerplateSettings()
        rules = settings.get_rules()
        names = [r.name for r in rules]
        assert "rule_a" in names
        assert "rule_b" in names

    def test_default_settings_returns_all_default_rules(self) -> None:
        settings = BoilerplateSettings(
            boilerplate_extra_rules="",
            boilerplate_disabled_rules="",
        )
        rules = settings.get_rules()
        assert len(rules) == len(DEFAULT_RULES)

    def test_multiple_disabled_rules_comma_separated(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setenv(
            "BOILERPLATE_DISABLED_RULES", "maven_build_output,package_lock_metadata"
        )
        settings = BoilerplateSettings()
        rules = settings.get_rules()
        disabled = {r.name for r in rules if not r.enabled}
        assert "maven_build_output" in disabled
        assert "package_lock_metadata" in disabled
